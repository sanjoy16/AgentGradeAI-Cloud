"""Plain-language teaching guidance, kept distinct from measured tool findings."""
import re


def readable(text):
    text = re.sub(r'(?:/[\w.\-]+)+/submission\.c', 'submission.c', str(text or ''))
    return text


def repair_cards(result):
    source=result.get('source','')
    cards=[]
    def add(title,where,why,change,example,test):
        cards.append(dict(title=title,where=where,why=why,change=change,example=example,test=test))
    lines=source.splitlines()
    for n,line in enumerate(lines,1):
        if re.search(r'\bint\s+main\s*\(\s*\)',line):
            add('Use the standard main declaration',f'Line {n}',
                'The declaration main() does not explicitly list its parameters. Using main(void) states that no arguments are expected.',
                'Replace int main() with int main(void).', 'int main(void) {',
                'Compile again with warnings enabled. The prototype warning should disappear.')
        if re.match(r'^\s*scanf\s*\(',line):
            add('Check whether input was read',f'Line {n}',
                'Source-review advice: a standalone scanf call ignores its return value. Failed input can leave the destination unchanged or uninitialized.',
                'For a single integer, continue only when scanf returns 1. Adapt the count for multiple inputs.',
                'if (scanf("%d", &n) != 1) {\n    puts("Invalid input");\n    return 1;\n}',
                'Try a letter and empty input. The program should reject them before calculating.')
    if 'factorial' in source.lower() and re.search(r'unsigned\s+long\s+long',source):
        add('Keep factorial within the numeric range','Input validation before the factorial loop',
            'Source-review advice: with a 64-bit unsigned long long, 20! fits and 21! does not. This is guidance, not a new verifier result.',
            'Check that n is between 0 and 20 before multiplying. Keep an existing equivalent check.',
            'if (n < 0 || n > 20) {\n    puts("Enter a number from 0 to 20");\n    return 1;\n}',
            '0 -> 1; 5 -> 120; 20 -> 2432902008176640000; reject -1 and 21.')
    raw='\n'.join(str(a.get('evidence','')) for a in result.get('agents',[]))
    if 'variableScope' in raw:
        add('Declare variables close to where they are used','Lines identified by the variableScope warnings',
            'This is a readability suggestion. It does not mean the factorial answer is wrong.',
            'Declare i inside the for loop and the accumulator inside the calculation block, if that is its only use.',
            'unsigned long long factorial = 1;\nfor (int i = 2; i <= n; ++i) {\n    factorial *= (unsigned long long)i;\n}',
            'Re-run Cppcheck and confirm the scope warnings are resolved. Check 0 and 5 again.')
    return cards[:8]


